// Writes every player-facing text, in the order a player meets it, to
// docs/STORY.md — for reviewing the story as one script.
// Run: node scripts/story.mjs   (bundles src/ with the esbuild that ships with vite)
import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";

const entry = `
import { initialState } from "./src/types";
import { buildFilesystem, fileContent, findNode, EGGS, TIDY_EGG, ROOT_EGG } from "./src/game/fs";
import { STAGES } from "./src/game/stage";
import { commands } from "./src/game/commands";
export { initialState, buildFilesystem, fileContent, findNode, EGGS, TIDY_EGG, ROOT_EGG, STAGES, commands };
`;
const out = await build({
  stdin: { contents: entry, resolveDir: process.cwd(), loader: "ts" },
  bundle: true, write: false, format: "esm", platform: "node",
  alias: { "@": "./src" }, logLevel: "error",
});
const m = await import("data:text/javascript;base64," + Buffer.from(out.outputFiles[0].text).toString("base64"));
const { initialState, buildFilesystem, fileContent, findNode, EGGS, TIDY_EGG, ROOT_EGG, STAGES, commands } = m;

const root = buildFilesystem();
const md = ["# Eggshell — the whole script, in order of appearance", "", "Generated by `scripts/story.mjs`. Do not edit by hand.", ""];
const block = (title, text) => md.push(`### ${title}`, "", "```", text.trimEnd(), "```", "");
const run = (cmd, args, state) => {
  const lines = [];
  commands[cmd](args, { state, print: (l) => lines.push(l), setState() {}, setCwd() {}, cwd: "/home/player", root,
    openEditor() {}, openMenu() {}, passwordPrompt() {}, sudoActive: false });
  return lines.join("\n");
};
const DIFFS = ["easy", "medium", "hard"];
// A file once, plus every difficulty variant that differs.
const file = (path, state) => {
  const node = findNode(root, path);
  const seen = new Map();
  for (const d of DIFFS) {
    const t = fileContent(node, { ...state, difficulty: d });
    seen.set(t, [...(seen.get(t) ?? []), d]);
  }
  for (const [t, ds] of seen) block(`${path}${seen.size > 1 ? `  (${ds.join(", ")})` : ""}`, t);
};
// One block per sub-step (state), each with its three tiers in order.
const hints = (i, states) => {
  const body = states.map((st, n) => {
    const step = STAGES[i].step?.(st);
    const head = states.length > 1 ? `[sub-step ${n + 1}${step ? `: ${step}` : ""}]\n` : "";
    return head + STAGES[i].hints.map((h, t) => `${t + 1}. ${typeof h === "function" ? h(st) : h}`).join("\n");
  });
  block(`hints for egg ${i + 1} (hint 1 = nudge, 2 = direction, 3 = exact)`, body.join("\n\n"));
};
const stage = (i, state) => {
  md.push(`## Egg ${i + 1} — ${STAGES[i].name}`, "", `Objective (eggs): ${STAGES[i].goal}`, "");
  if (STAGES[i].announce) md.push(`Door announcement: ${STAGES[i].announce}`, "");
};

let s = { ...initialState, started: true }; // `start` itself first asks the name
md.push("## Opening", "", "Banner: see `src/App.tsx` (EggshellOS 1.0 — eggshell.local / Last login by hen / type `start`).", "");
block("start  (after \"What's your name?\")", run("start", [], { ...s, playerName: "<name>" }));
block("help (egg 1)", run("help", [], s));

stage(0, s);
file("/home/player/README.txt", s); file("/home/player/notes.txt", s); file("/etc/wifi.json", s);
hints(0, [s]);
s = { ...s, wifiConnected: true };
file(EGGS[0], s);

stage(1, s);
file("/home/player/documents/clue2.riddle", s);
hints(1, [s, { ...s, createdMagicDir: true }]);
s = { ...s, createdMagicDir: true, createdTokenFile: true, eggsFound: [EGGS[0]] };
file(EGGS[1], s);

stage(2, s);
file("/home/player/secrets/quota.txt", s);
const onlyHidden = { ...s, userCreated: s.userCreated.filter((u) => !u.path.endsWith(".tmp") || u.path.split("/").pop().startsWith(".")) };
hints(2, [s, onlyHidden, { ...s, userCreated: s.userCreated.filter((u) => !u.path.endsWith(".tmp")) }]);
block("rm *.tmp (the hidden one is left)", "~/secrets is still over quota: something temporary is left. Not every file shows up in a plain listing.");
file("/home/player/secrets/quota.txt", onlyHidden);
block(EGGS[2], TIDY_EGG);
s = { ...s, userCreated: [{ type: "file", path: EGGS[2], content: TIDY_EGG }], eggsFound: EGGS.slice(0, 3) };
file("/home/player/secrets/quota.txt", s);

stage(3, s);
file("/home/player/secrets/secrets.cfg", s); file("/home/player/secrets/editor-tips.txt", s);
hints(3, [s]);
s = { ...s, secretsUnlocked: true };
file(EGGS[3], s);

stage(4, s);
s = { ...s, eggsFound: EGGS.slice(0, 4) };
file("/home/player/vault/sudo_clue.json", s); file("/home/player/vault/how-to-sudo.txt", s); file("/etc/privilege.cfg", s);
hints(4, [s, { ...s, knowsSudoPassword: true }]);
s = { ...s, knowsSudoPassword: true, adminUnlocked: true };
file(EGGS[4], s);

stage(5, s);
s = { ...s, eggsFound: EGGS.slice(0, 5) };
hints(5, [s, { ...s, rootEntered: true }]);
block(EGGS[5], ROOT_EGG);

stage(6, s);
s = { ...s, eggsFound: EGGS.slice(0, 6) };
hints(6, [s]);
file("/var/log/syslog", s);
file(EGGS[6], s);
block("eggs (win)", run("eggs", [], { ...s, eggsFound: EGGS }));

mkdirSync("docs", { recursive: true });
writeFileSync("docs/STORY.md", md.join("\n"));
console.log(`docs/STORY.md: ${md.length} lines`);
